// Run with node scripts/check-casting.cjs. No phone/TV required.
const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('./test-typescript.cjs');
const source = fs.readFileSync('entry/src/main/ets/pages/PlayerPage.ets', 'utf8');
const methods = source.slice(source.indexOf('  private async startRemotePlayback('), source.indexOf('  /** 把播放状态同步给投播会话'));
const deviceListener = source.slice(source.indexOf('  private bindCastSession('), source.indexOf('  private releaseCastSession('));
const controls = source.slice(source.indexOf('  private dismissPlayerControls()'), source.indexOf('  private scheduleHideControls()'));
const callbacks = source.slice(source.indexOf('  private bindCallbacks()'), source.indexOf('  /**\n   * 离线播放自愈'));
const compiled = ts.transpile('class TestPlayer {\n' + deviceListener + controls + callbacks + methods + '\n}', {target: ts.ScriptTarget.ES2020});
let resolveUrl;
const Player = vm.runInNewContext(compiled + '\nTestPlayer', {console, CastBackgroundTask:{stop:async()=>{}}, CastResume:{clear:()=>{},synchronize:async()=>null}, avSession:{AVCastCategory:{CATEGORY_REMOTE:1},ConnectionState:{STATE_CONNECTED:1,STATE_DISCONNECTED:0}}, PlayUrlResolver: {resolveSharePage: () => resolveUrl()}});
async function run() {
  const p = new Player();
  p.rememberCast = () => {};
  let started;
  let toast = '';
  let prepared;
  const calls = [];
  p.castController = {prepare: async item => {prepared = item; calls.push('prepare');}, start: async item => {started = item; calls.push('start');}};
  p.dropScreen = () => {};
  p.ensureEpisodesLoaded = async () => {};
  p.playableEpisode = () => ({url: 'https://example.com/share'});
  p.toast = message => {toast = message;};
  p.vodId = 'test'; p.currentEp = 2; p.title = 'Test'; p.positionMs = 5000; p.durationMs = 60000;
  resolveUrl = async () => {p.positionMs = 0; return 'https://example.com/video.m3u8';};
  assert.equal(await p.startRemotePlayback(), true);
  assert.deepEqual(calls, ['prepare', 'start']);
  assert.equal(prepared, started);
  assert.equal(started.description.mediaType, 'VIDEO');
  assert.equal(started.description.mediaUri, 'https://example.com/video.m3u8');
  assert.equal(started.description.startPosition, 5000);
  started = undefined;
  calls.length = 0;
  resolveUrl = async () => 'fd://123';
  assert.equal(await p.startRemotePlayback(), false);
  assert.equal(started, undefined); assert.ok(toast);
  assert.deepEqual(calls, []);
  resolveUrl = async () => {p.castController = null; return 'https://example.com/video.m3u8';};
  assert.equal(await p.startRemotePlayback(), false);
  assert.equal(started, undefined);
  const controller = p.castController = {prepare: async () => {p.castController = null;}, start: async () => {throw new Error('must not start after disconnect');}};
  resolveUrl = async () => 'https://example.com/video.m3u8';
  assert.equal(await p.startRemotePlayback(), false);
  p.controlsVisible = true;
  p.showSpeeds = p.showEpisodes = p.showSources = true;
  p.dismissPlayerControls();
  assert.equal(p.controlsVisible, false);
  assert.equal(p.showSpeeds || p.showEpisodes || p.showSources, false);
  p.player = {};
  p.bindCallbacks();
  p.castController = {};
  p.errorText = ''; p.buffering = false; p.durationMs = 60000;
  p.player.onError('local decoder failed');
  p.player.onBuffering(0);
  p.player.onPrepared(100);
  assert.equal(p.errorText, '');
  assert.equal(p.buffering, false);
  assert.equal(p.durationMs, 60000);
  p.castController = null;
  p.clearStall = () => {}; p.clearWatchdog = () => {};
  p.player.onError('local decoder failed');
  assert.equal(p.errorText, 'local decoder failed');
  let deviceChanged;
  const session = {on: (name, callback) => {deviceChanged = callback;}};
  p.castSession = session; p.castController = {off:()=>{}}; p.released = false;
  p.applyLocalRotation = p.setLandscape = p.holdScreen = p.saveProgress = () => {};
  p.player.pause = () => {};
  p.bindCastSession(session);
  deviceChanged(0, {devices:[]});
  assert.equal(p.castController, null);
  assert.equal(p.localResumePending, true);
  assert.equal(p.playing, false);
  let pauses = 0;
  p.player.pause = () => {pauses++;};
  p.player.onPlayStateChanged(true);
  assert.equal(pauses, 1);
  const disconnectOrder = [];
  p.castController = {off:()=>{},sendControlCommand: async command => {disconnectOrder.push(command.command);}};
  p.castSession = {stopCasting: async () => {disconnectOrder.push('disconnect');}};
  await Promise.all([p.disconnectCast(), p.disconnectCast()]);
  assert.equal(p.castDisconnecting, false);
  assert.deepEqual(disconnectOrder, ['stop', 'disconnect']);
  assert.equal(p.castController, null);
  assert.equal(p.localResumePending, true);
  assert.equal(p.playing, false);
  p.positionMs = 1200000; p.durationMs = 2400000;
  p.player.onProgress(0, 100); p.player.onPrepared(100);
  assert.equal(p.positionMs, 1200000); assert.equal(p.durationMs, 2400000);
  assert.equal(p.showCastConnection, false);
  console.log('PASS: TV receives network URL and resume position; local URLs and disconnected requests are rejected.');
}
run().catch(error => {console.error(error); process.exitCode = 1;});
